from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class ChainStatus(str, Enum):
    draft = 'draft'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class ChainNodeStatus(str, Enum):
    pending = 'pending'
    running = 'running'
    completed = 'completed'
    empty = 'empty'
    failed = 'failed'
    blocked = 'blocked'
